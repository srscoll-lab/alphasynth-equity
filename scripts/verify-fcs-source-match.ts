import assert from 'node:assert/strict';
import {containsReportedNumber,containsReportingPeriod} from '../src/fundamental-review-source-match.ts';
assert(containsReportedNumber('PAT (2,380)',-2380));
assert(!containsReportedNumber('PAT (2,380)',2380));
assert(containsReportedNumber('PAT margin (1.0%)',-1));
assert(containsReportedNumber('13.30',13.3));
assert(!containsReportedNumber('1.33 113.3 13',13.3));
assert(containsReportedNumber('Revenue 3,66,820.00',366820));
assert(containsReportedNumber('Revenue 1,23,45,678.90',12345678.9));
assert(containsReportedNumber('Revenue 1,234,567.89',1234567.89));
assert(containsReportedNumber('Loss (1,23,456.00)',-123456));
assert(!containsReportedNumber('Revenue 3,66,820.00',66820));
assert(!containsReportedNumber('Revenue 3,66,820.00',820));
assert(!containsReportedNumber('Revenue 3,66,820.00',3668.2));
assert(!containsReportedNumber('Corrupt 12,34.56',1234.56));
assert(!containsReportedNumber('Corrupt 2,1S4.45',2154.45));
assert(containsReportingPeriod('Quarter ended Jun’26 Jun’25','Q1 FY27','2026-06-30'));
assert(containsReportingPeriod('Quarter ended Jun’26 Jun’25','Q1 FY26','2025-06-30'));
assert(!containsReportingPeriod('Quarter ended Jun’26','Q1 FY26','2025-06-30'));
assert(!containsReportingPeriod('Jun-26','Q1 FY27','2026-06-29'));
assert(!containsReportingPeriod('June 20260','Q1 FY27','2026-06-30'));
assert(containsReportingPeriod('Reporting date 30-06-2026','Q1 FY27','2026-06-30'));
assert(containsReportingPeriod('Reporting date 30.06.2026','Q1 FY27','2026-06-30'));
assert(!containsReportingPeriod('Reporting date 30-06-2025','Q1 FY27','2026-06-30'));
assert(!containsReportingPeriod('Reporting date 130-06-2026','Q1 FY27','2026-06-30'));
assert(!containsReportingPeriod('Reporting date 30-06-20260','Q1 FY27','2026-06-30'));
console.log('Source matching: accounting negatives, exact numbers, abbreviated quarter headers and wrong periods passed.');
